import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  dedupeIdenticalModuleSlides,
  ensureUniqueSlideIds,
  insertSlidesIntoCourse,
} from './courseSlideEdits.ts';

const DS_CONTENT = '- Generated from high-pressure boiler steam\n- Reduces cracking temperature locally\n- Prevents coke build up in the radiant coils';

function dilution(id: string) {
  return {
    id,
    type: 'tabbed-horizontal',
    title: 'Dilution Steam Generation and Its Importance',
    content: DS_CONTENT,
    voiceOverText: 'Dilution steam is superheated water vapor generated by the plant boiler.',
  };
}

test('insert after a host slide does not clone that host or the rest of the module', () => {
  const course = {
    modules: [{
      id: 'm4',
      title: 'Auxiliary Systems',
      slides: [
        { id: 'qo', type: 'content', title: 'Quench Oil Tower', content: '- Quench oil removes heat from cracked gas' },
        { id: 'qw', type: 'content', title: 'Quench Water Tower', content: '- Quench water condenses dilution steam' },
        dilution('ds'),
        { id: 'int', type: 'content', title: 'Integrated Utility Systems', content: '- Steam, water, and fuel systems share headers' },
        { id: 'kc', type: 'quiz', title: 'Knowledge Check: Auxiliary Systems', content: '', data: { questionText: 'Why is dilution steam injected with the feed?' } },
      ],
    }],
  };
  const incoming = [
    { id: 'n1', type: 'content', title: 'Very High Pressure Steam Generation', content: '- VHP steam drives the cracked-gas compressor' },
    { id: 'n2', type: 'content', title: 'Refrigerant Cascades', content: '- Cascades recover cold for the demethanizer' },
    { id: 'n3', type: 'content', title: 'Heat Integration Strategy', content: '- Pinch analysis sets exchanger duties' },
  ];
  const spliced = insertSlidesIntoCourse(course, incoming, {
    placement: 'after',
    currentSlide: { id: 'ds' },
  });
  assert.ok(spliced);
  const titles = spliced!.course.modules[0].slides.map((s: any) => s.title);
  assert.deepEqual(titles, [
    'Quench Oil Tower',
    'Quench Water Tower',
    'Dilution Steam Generation and Its Importance',
    'Very High Pressure Steam Generation',
    'Refrigerant Cascades',
    'Heat Integration Strategy',
    'Integrated Utility Systems',
    'Knowledge Check: Auxiliary Systems',
  ]);
  const dsCount = titles.filter((t: string) => t.startsWith('Dilution Steam')).length;
  assert.equal(dsCount, 1);
});

test('insert skips generated clones of slides already in the module', () => {
  const course = {
    modules: [{
      slides: [dilution('ds'), { id: 'int', type: 'content', title: 'Integrated Utility', content: '- Shared headers across steam and water' }],
    }],
  };
  const spliced = insertSlidesIntoCourse(course, [
    { ...dilution('clone'), id: 'clone' },
    { id: 'vhp', type: 'content', title: 'Very High Pressure Steam Generation', content: '- VHP steam drives the cracked-gas compressor' },
  ], { placement: 'after', currentSlide: { id: 'ds' } });
  assert.ok(spliced);
  const titles = spliced!.course.modules[0].slides.map((s: any) => s.title);
  assert.equal(titles.filter((t: string) => t.startsWith('Dilution Steam')).length, 1);
  assert.ok(titles.includes('Very High Pressure Steam Generation'));
});

test('identical copies already in a module are dropped, distinct knowledge checks are kept', () => {
  const course = {
    modules: [{
      slides: [
        dilution('ds-a'),
        { id: 'vhp', type: 'content', title: 'Very High Pressure Steam Generation', content: '- VHP steam drives the cracked-gas compressor' },
        dilution('ds-b'),
        { id: 'kc1', type: 'quiz', title: 'Knowledge Check: Quench Systems', data: { questionText: 'What does quench oil remove from cracked gas?' } },
        { id: 'kc2', type: 'quiz', title: 'Knowledge Check: Utility Systems', data: { questionText: 'Which header is shared by steam and boiler feed water?' } },
        dilution('ds-c'),
      ],
    }],
  };
  const next = dedupeIdenticalModuleSlides(course);
  const titles = next.modules[0].slides.map((s: any) => s.title);
  assert.equal(titles.filter((t: string) => t.startsWith('Dilution Steam')).length, 1);
  assert.ok(titles.includes('Knowledge Check: Quench Systems'));
  assert.ok(titles.includes('Knowledge Check: Utility Systems'));
  assert.equal(next.modules[0].slides.length, 4);
});

test('ensureUniqueSlideIds also drops identical content copies', () => {
  const course = ensureUniqueSlideIds({
    modules: [{ slides: [dilution('same'), dilution('same'), dilution('other')] }],
  });
  assert.equal(course.modules[0].slides.length, 1);
  assert.equal(course.modules[0].slides[0].id, 'same');
});

